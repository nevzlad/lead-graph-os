import inspect

BASE_TEMPLATES = {
    "news": (
        "Перепиши новость в стиле информационного Telegram-канала. "
        "Сделай текст уникальным: измени порядок блоков, используй синонимы, переформулируй предложения. "
        "Сохрани все ключевые факты, даты, имена. "
        "Не копируй структуру оригинала. "
        "Ответ верни ТОЛЬКО текстом, без JSON, без пояснений."
    ),
    "blog": (
        "Перепиши пост для блога в разговорном, живом стиле. "
        "Сделай текст уникальным: измени порядок абзацев, перефразируй, добавь свои формулировки. "
        "Ответ верни ТОЛЬКО текстом, без JSON, без пояснений."
    ),
    "shop": (
        "Перепиши описание товара в продающем стиле для Telegram. "
        "Сделай текст уникальным: переформулируй преимущества, измени порядок блоков. "
        "Ответ верни ТОЛЬКО текстом, без JSON, без пояснений."
    ),
}

RETRY_INSTRUCTIONS = {
    "too_short": (
        "\n\nПРЕДУПРЕЖДЕНИЕ: Предыдущий ответ был слишком коротким (меньше {min_len} символов). "
        "Напиши развёрнутый текст объёмом не менее {min_len} символов. "
        "Раскрой тему подробно."
    ),
    "wrong_language": (
        "\n\nПРЕДУПРЕЖДЕНИЕ: Предыдущий ответ был на неверном языке. "
        "Ответь строго на языке: {target_lang}. "
        "Проверь, что весь текст написан на этом языке."
    ),
    "too_similar": (
        "\n\nПРЕДУПРЕЖДЕНИЕ: Предыдущий ответ слишком похож на исходный текст. "
        "Измени структуру: переставь абзацы местами, замени формулировки, используй другой порядок изложения. "
        "Сделай текст полностью уникальным."
    ),
}


def build_prompt(
    niche: str,
    text: str,
    target_lang: str | None = None,
    validation_error: str | None = None,
    min_len: int = 100,
) -> str:
    base = BASE_TEMPLATES.get(niche, BASE_TEMPLATES["news"])
    parts = [base]

    if target_lang and target_lang != "ru":
        parts.append(f"\n\nВажно: ответ должен быть на языке: {target_lang}. "
                     f"Используй {target_lang} для всего текста.")

    parts.append(f"\n\nИсходный текст:\n{text[:3000]}")

    if validation_error:
        instruction = RETRY_INSTRUCTIONS.get(validation_error)
        if instruction:
            parts.append(instruction.format(min_len=min_len, target_lang=target_lang or "ru"))

    return "".join(parts)
