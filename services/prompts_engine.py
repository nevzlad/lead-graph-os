from config import settings


class RewritePromptBuilder:
    SYSTEM_CORE = (
        "Ты — профессиональный редактор контента для Telegram-канала. "
        "Выполни следующие 5 инструкций строго по порядку:\n\n"
        "1. ПОЛНЫЙ РЕРАЙТ. Сохрани все ключевые факты, даты, имена, цифры и ссылки из исходного текста. "
        "Измени синтаксис и порядок блоков: переставь абзацы местами, замени структуру предложений, "
        "используй синонимы и переформулировки. Не копируй прямые фрагменты длиннее 5 слов подряд.\n"
        "2. ПЕРЕВОД. Если целевой язык отличается от языка оригинала — выполни полный перевод всего текста "
        "на {target_lang}. Если язык совпадает — этот шаг пропускается.\n"
        "3. ФОРМАТИРОВАНИЕ. Оформи текст с HTML-разметкой: используй <b>жирный</b> для заголовка и ключевых "
        "мыслей, <i>курсив</i> для акцентов, маркированные списки <code>&lt;ul&gt;&lt;li&gt;...</code> где уместно, "
        "разделяй смысловые блоки пустыми строками. Заголовок вынеси в начало и оберни в <b>.</b>\n"
        "4. УНИКАЛЬНОСТЬ. Убедись, что итоговый текст отличается от исходного более чем на 70%: "
        "замени не менее трети лексики на синонимы, перестрой каждое второе предложение, "
        "измени порядок абзацев. Используй профессиональную лексику по теме.\n"
        "5. ЗАПРЕТ ГАЛЛЮЦИНАЦИЙ. Не выдумывай даты, цифры, статистику, имена, ссылки или факты, "
        "которых нет в исходном тексте. Если в оригинале нет информации — не добавляй её. "
        "Не используй шаблонные фразы-клише.\n\n"
        "Ответ верни ТОЛЬКО финальным текстом. Без JSON, без пояснений, без лишних символов."
    )

    NICHE_ADAPT = {
        "news": (
            "\n\nДополнительно для новостного канала: пиши информативно, но сжато. "
            "Первый абзац — суть новости (кто, что, где, когда). Последующие — детали и контекст."
        ),
        "blog": (
            "\n\nДополнительно для блога: используй разговорный, вовлекающий тон. "
            "Добавь риторические вопросы или примеры из жизни. Читатель должен чувствовать диалог."
        ),
        "shop": (
            "\n\nДополнительно для магазина: выдели выгоды и преимущества товара. "
            "Используй продающие триггеры (ограниченность, социальное доказательство). "
            "Добавь маркированный список характеристик."
        ),
    }

    RETRY_INSTRUCTIONS = {
        "too_short": (
            "\n\nПРЕДУПРЕЖДЕНИЕ: Предыдущий ответ слишком короткий (меньше {min_len} символов). "
            "Напиши развёрнутый текст объёмом не менее {min_len} символов. Раскрой тему подробно, "
            "добавь контекст и дополнительные детали."
        ),
        "wrong_language": (
            "\n\nПРЕДУПРЕЖДЕНИЕ: Предыдущий ответ на неверном языке. "
            "Весь текст должен быть строго на языке: {target_lang}. Проверь каждое предложение."
        ),
        "too_similar": (
            "\n\nПРЕДУПРЕЖДЕНИЕ: Предыдущий ответ слишком похож на исходный текст. "
            "Перестрой каждое предложение заново: измени порядок слов, используй другие грамматические "
            "конструкции, замени минимум 50% лексики на синонимы. Сделай текст полностью уникальным."
        ),
    }

    def build_rewrite_prompt(
        self,
        text: str,
        target_lang: str | None = None,
        niche: str = "news",
        validation_error: str | None = None,
        min_len: int | None = None,
    ) -> str:
        lang = target_lang or settings.TARGET_LANGUAGE
        parts = [self.SYSTEM_CORE.format(target_lang=lang)]

        niche_extra = self.NICHE_ADAPT.get(niche)
        if niche_extra:
            parts.append(niche_extra)

        parts.append(f"\n\nИсходный текст для рерайта:\n{text[:4000]}")

        if validation_error:
            instruction = self.RETRY_INSTRUCTIONS.get(validation_error)
            if instruction:
                parts.append(
                    instruction.format(
                        min_len=min_len or settings.LLM_MIN_CONTENT_LENGTH,
                        target_lang=lang,
                    )
                )

        return "".join(parts)


_builder = RewritePromptBuilder()


def build_prompt(
    niche: str,
    text: str,
    target_lang: str | None = None,
    validation_error: str | None = None,
    min_len: int | None = None,
) -> str:
    return _builder.build_rewrite_prompt(
        text=text,
        target_lang=target_lang,
        niche=niche,
        validation_error=validation_error,
        min_len=min_len,
    )
